// Generate src/api/types.gen.ts from the backend's JSON Schemas
// (src/api/schemas/*.schema.json, written by `make schemas`), so API drift
// fails the build. `--check` exits 1 when the committed file is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "src", "api", "schemas");
const out = join(here, "..", "src", "api", "types.gen.ts");

// Pydantic titles every property; json2ts would emit an alias for each
// ("Seq1", "Type1"). Keep titles only on definitions and the root.
function untitle(node, keep) {
  if (Array.isArray(node)) return node.forEach((n) => untitle(n, false));
  if (!node || typeof node !== "object") return;
  if (!keep) delete node.title;
  // Responses always carry every field (the server dumps defaults and
  // nulls), so a defaulted field is required here; nullable stays nullable.
  if (node.type === "object" && node.properties) node.required = Object.keys(node.properties);
  for (const [k, v] of Object.entries(node)) {
    if (k === "$defs" || k === "definitions") {
      for (const d of Object.values(v)) untitle(d, true);
    } else if (k === "properties" && v && typeof v === "object") {
      // Keys here are field names (a field may be called "title").
      for (const prop of Object.values(v)) untitle(prop, false);
    } else untitle(v, false);
  }
}

const pascal = (s) => s.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
let text =
  "/* eslint-disable */\n// Generated by scripts/gen-types.mjs from src/api/schemas. Do not edit.\n";
const seen = new Set();
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith(".schema.json"))
  .sort()) {
  const schema = JSON.parse(readFileSync(join(dir, file), "utf8"));
  const name = pascal(file.replace(".schema.json", ""));
  untitle(schema, true);
  schema.title ??= name;
  let ts = await compile(schema, name, {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
    unreachableDefinitions: false,
    style: { printWidth: 100 },
  });
  // Shared definitions (Provenance, Warning, …) appear in several schemas:
  // keep the first copy of each exported declaration.
  ts = ts
    .split(/\n(?=export )/)
    .filter((decl) => {
      const m = decl.match(/^export (?:interface|type) (\w+)/);
      if (!m) return true;
      if (seen.has(m[1])) return false;
      seen.add(m[1]);
      return true;
    })
    .join("\n");
  text += `\n// ── ${file} ──\n` + ts;
}

// Exactly one final newline (what the repo's end-of-file hook leaves).
text = text.trimEnd() + "\n";

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/api/types.gen.ts is stale: run `npm run types`.");
    process.exit(1);
  }
  console.error("types.gen.ts is up to date.");
} else {
  writeFileSync(out, text);
  console.error(`wrote ${out}`);
}
