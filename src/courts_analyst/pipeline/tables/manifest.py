"""The table manifest (``data/manifest/tables.yaml``) and how we discover it.

The manifest is committed. It lists, for every table family and edition in
scope, the landing page, the xlsx/PDF URLs and (once fetched) their sha256.
The build reads only the manifest and the raw cache, so it runs offline and
reproducibly; ``discover`` is the only step that crawls uscourts.gov.

Discovery walks ``/data-table-numbers/<slug>`` (every edition of one table,
across series, paginated), keeps the landing pages for our series and years,
and reads each landing page's file links. File folders differ by edition
(``data_tables/``, ``2025-01/``, ``document/``), so URLs are never guessed.
"""

from __future__ import annotations

import html
import re
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urljoin

import yaml

from courts_analyst.pipeline.tables.families import FAMILIES, Family
from courts_analyst.pipeline.tables.fetch import Fetcher
from courts_analyst.pipeline.tables.records import SERIES_SLUGS, Series, edition_id

BASE = "https://www.uscourts.gov"
MANIFEST_VERSION = 1


@dataclass
class FileEntry:
    url: str
    sha256: str | None = None


@dataclass
class TableEntry:
    family: str
    series: Series
    table_code: str
    edition: str
    period_end: date
    landing_url: str
    title: str | None = None
    files: dict[str, FileEntry] = field(default_factory=dict)

    @property
    def primary_format(self) -> str:
        """xlsx when published (exact values), else PDF."""
        return "xlsx" if "xlsx" in self.files else "pdf"

    def file_id(self, fmt: str) -> str:
        return f"{self.edition}:{self.table_code}:{fmt}"

    def raw_path(self, raw_dir: Path, fmt: str) -> Path:
        name = self.files[fmt].url.rsplit("/", 1)[-1]
        return raw_dir / self.edition / name


@dataclass
class Manifest:
    tables: list[TableEntry]
    generated: str | None = None

    def sorted(self) -> Manifest:
        order = {k: i for i, k in enumerate(FAMILIES)}
        self.tables.sort(key=lambda t: (order.get(t.family, 99), t.period_end))
        return self


def load_manifest(path: Path) -> Manifest:
    data = yaml.safe_load(path.read_text()) or {}
    tables = [
        TableEntry(
            family=t["family"],
            series=Series(t["series"]),
            table_code=str(t["table_code"]),
            edition=t["edition"],
            period_end=date.fromisoformat(str(t["period_end"])),
            landing_url=t["landing_url"],
            title=t.get("title"),
            files={
                fmt: FileEntry(url=f["url"], sha256=f.get("sha256"))
                for fmt, f in (t.get("files") or {}).items()
            },
        )
        for t in data.get("tables", [])
    ]
    return Manifest(tables=tables, generated=data.get("generated"))


def dump_manifest(manifest: Manifest, path: Path) -> None:
    out: dict[str, Any] = {
        "version": MANIFEST_VERSION,
        "generated": manifest.generated,
        "source": f"{BASE}/data-table-numbers/",
        "tables": [
            {
                "family": t.family,
                "series": t.series.value,
                "table_code": t.table_code,
                "edition": t.edition,
                "period_end": t.period_end.isoformat(),
                "landing_url": t.landing_url,
                "title": t.title,
                "files": {
                    fmt: {"url": f.url, "sha256": f.sha256}
                    for fmt, f in sorted(t.files.items())
                },
            }
            for t in manifest.sorted().tables
        ],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Official uscourts.gov tables in scope (Phase 1). Generated by\n"
        "# `python -m courts_analyst.pipeline.tables discover`; sha256 pins are\n"
        "# filled by `fetch`. Published editions must not change: a new sha on a\n"
        "# pinned file fails the fetch (EditionChangedError).\n"
    )
    path.write_text(
        header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=100)
    )


# ── Discovery ───────────────────────────────────────────────────────────────

_LANDING = re.compile(
    r'href="(/data-news/data-tables/(\d{4})/(\d{2})/(\d{2})/([a-z-]+)/([a-z0-9.-]+))"'
)
_PAGE = re.compile(r'href="\?page=(\d+)"|href="[^"]*[?&]page=(\d+)[^"]*"')
_TITLE = re.compile(r"<title>([^<]+)</title>", re.I)


def listing_urls(fetcher: Fetcher, family: Family) -> list[tuple[date, str]]:
    """All landing pages for ``family`` (its series, Sep 30 editions in scope)."""
    base = f"{BASE}/data-table-numbers/{family.number_slug}"
    seen_pages = {0}
    queue = [0]
    found: dict[str, date] = {}
    while queue:
        page = queue.pop(0)
        text = fetcher.get_text(base if page == 0 else f"{base}?page={page}")
        for m in _LANDING.finditer(text):
            href, y, mo, d, series_slug, _code = m.groups()
            if series_slug != SERIES_SLUGS[family.series]:
                continue
            end = date(int(y), int(mo), int(d))
            if end.month == 9 and end.year >= family.first_edition:
                found[urljoin(BASE, href)] = end
        for m in _PAGE.finditer(text):
            n = int(m.group(1) or m.group(2))
            if n not in seen_pages and n < 50:
                seen_pages.add(n)
                queue.append(n)
    return sorted(((d, u) for u, d in found.items()), key=lambda x: x[0])


def landing_files(page_html: str, family: Family, period_end: date) -> dict[str, str]:
    """File URLs on a landing page for this table and edition, by format."""
    mmdd = f"{period_end.month:02d}{period_end.day:02d}"
    pat = re.compile(
        rf'href="([^"]*/{re.escape(family.stem)}_{mmdd}\.{period_end.year}\.(xlsx|pdf))"',
        re.I,
    )
    out: dict[str, str] = {}
    for m in pat.finditer(page_html):
        out.setdefault(m.group(2).lower(), urljoin(BASE, html.unescape(m.group(1))))
    return out


def discover(
    fetcher: Fetcher,
    families: list[Family],
    previous: Manifest | None = None,
    today: date | None = None,
) -> Manifest:
    """Crawl uscourts.gov for every edition of ``families``; keep existing pins."""
    pins = {
        (t.edition, t.table_code, fmt): f.sha256
        for t in (previous.tables if previous else [])
        for fmt, f in t.files.items()
    }
    tables: list[TableEntry] = []
    for family in families:
        for end, url in listing_urls(fetcher, family):
            page = fetcher.get_text(url)
            files = landing_files(page, family, end)
            if not files:
                continue
            title = _TITLE.search(page)
            ed = edition_id(family.series, end)
            tables.append(
                TableEntry(
                    family=family.key,
                    series=family.series,
                    table_code=family.table_code,
                    edition=ed,
                    period_end=end,
                    landing_url=url,
                    title=html.unescape(title.group(1)).strip() if title else None,
                    files={
                        fmt: FileEntry(u, pins.get((ed, family.table_code, fmt)))
                        for fmt, u in files.items()
                    },
                )
            )
    return Manifest(
        tables=tables, generated=(today or date.today()).isoformat()
    ).sorted()
