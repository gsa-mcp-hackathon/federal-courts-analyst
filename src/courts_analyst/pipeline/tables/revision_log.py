"""Render ``docs/revision-log.md`` from the built catalog.

The document is generated; never edit it by hand. Phase 5 serves the same
content as an MCP resource.
"""

from __future__ import annotations

from pathlib import Path

import duckdb


def _fmt(value: float | None, decimals: int | None) -> str:
    if value is None:
        return "—"
    d = decimals if decimals is not None else 0
    d = min(d, 1)  # the log is for reading; the catalog keeps full precision
    return f"{value:,.{d}f}"


def _signed(value: float | None, decimals: int) -> str:
    if value is None:
        return "—"
    return f"{value:+,.{min(decimals, 1)}f}"


def render(con: duckdb.DuckDBPyConnection) -> str:
    counts = con.execute(
        """
        SELECT (SELECT COUNT(*) FROM source_file WHERE parsed),
               (SELECT COUNT(DISTINCT edition) FROM observation),
               (SELECT COUNT(DISTINCT table_code) FROM observation),
               (SELECT COUNT(*) FROM observation),
               (SELECT COUNT(*) FROM revision_log),
               (SELECT COUNT(*) FROM revision_log WHERE court = 'US')
        """
    ).fetchone()
    assert counts is not None
    files, editions, tables, obs, revised, revised_us = counts

    lines = [
        "# Revision log: official figures that changed between editions",
        "",
        "> Generated by `python -m courts_analyst.pipeline.tables build` from the",
        "> official uscourts.gov tables. Do not edit by hand.",
        "",
        f"The catalog holds **{obs:,} published values** from **{files} files** "
        f"({tables} tables, {editions} editions). **{revised:,} figures** were printed "
        f"with a different value in a later edition; **{revised_us}** of them are "
        "national totals.",
        "",
        "A figure counts as revised when a later edition prints a different value at "
        "the precision both editions display (a PDF showing 355 and a workbook storing "
        "355.12 are the same figure). Editions are ordered by publication: Judicial "
        "Business (JB) first, then Judicial Facts and Figures (JFF) for the same year.",
        "",
        "Why a figure changed is **not** stated in the tables. Where the tables' own "
        "notes point to a cause (for example, a change in case weights or methodology) "
        "we quote them in `docs/`; anything else is our inference and is labelled so.",
        "",
        "## National figures",
        "",
    ]
    rows = con.execute(
        """
        SELECT r.measure_id, m.label, r.fiscal_year, r.first_edition, r.first_value,
               r.first_decimals, r.latest_edition, r.latest_value, r.latest_decimals,
               r.delta, r.editions, r.values, m.decimals
        FROM revision_log r JOIN measure_def m USING (measure_id)
        WHERE r.court = 'US'
        ORDER BY m.weighted DESC, r.measure_id, r.fiscal_year
        """
    ).fetchall()
    current = None
    for (
        mid,
        label,
        fy,
        fe,
        fv,
        fd,
        le,
        lv,
        ld,
        delta,
        eds,
        vals,
        mdec,
    ) in rows:
        if mid != current:
            if current is not None:
                lines.append("")
            lines += [
                f"### {label}",
                "",
                f"`{mid}`",
                "",
                "| FY | First published | Latest | Change | Every edition |",
                "| --- | --- | --- | --- | --- |",
            ]
            current = mid
        chain = " → ".join(
            f"{_fmt(v, mdec)} ({e})" for e, v in zip(eds, vals, strict=True)
        )
        lines.append(
            f"| {fy} | {_fmt(fv, fd)} ({fe}) | {_fmt(lv, ld)} ({le}) | "
            f"{_signed(delta, mdec)} | {chain} |"
        )
    if not rows:
        lines.append("No national figures were revised.")
    lines.append("")

    lines += ["## District and circuit figures", ""]
    summary = con.execute(
        """
        SELECT m.label, r.measure_id, COUNT(*) AS n, COUNT(DISTINCT r.court) AS courts
        FROM revision_log r JOIN measure_def m USING (measure_id)
        WHERE r.court <> 'US'
        GROUP BY ALL ORDER BY n DESC
        """
    ).fetchall()
    if summary:
        lines += [
            "| Measure | Revised figures | Courts |",
            "| --- | --- | --- |",
            *[f"| {label} (`{mid}`) | {n:,} | {c} |" for label, mid, n, c in summary],
            "",
            "Largest district revisions (by absolute change):",
            "",
            "| Court | Measure | FY | First published | Latest | Change |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        top = con.execute(
            """
            SELECT c.citation, r.court, m.label, r.fiscal_year, r.first_edition,
                   r.first_value, r.latest_edition, r.latest_value, r.delta, m.decimals
            FROM revision_log r JOIN measure_def m USING (measure_id)
            JOIN court c ON c.code = r.court
            WHERE r.court <> 'US'
            ORDER BY ABS(r.delta) DESC, r.court LIMIT 25
            """
        ).fetchall()
        for cit, code, label, fy, fe, fv, le, lv, delta, dec in top:
            lines.append(
                f"| {cit or code} | {label} | {fy} | {_fmt(fv, dec)} ({fe}) | "
                f"{_fmt(lv, dec)} ({le}) | {_signed(delta, dec)} |"
            )
        lines += [
            "",
            "The full list is in the `revision_log` table of `courts.duckdb` and in "
            "`data/build/parquet/revision_log.parquet`.",
        ]
    else:
        lines.append("No district or circuit figures were revised.")
    lines.append("")
    return "\n".join(lines)


def write_revision_log(db_path: Path, out: Path) -> str:
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        text = render(con)
    finally:
        con.close()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return text
