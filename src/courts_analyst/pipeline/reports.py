"""Generated reports: ``python -m courts_analyst.pipeline.reports variance``.

``docs/variance-report.md`` reconciles every district, circuit and the nation
for FY2016–FY2025 (civil cases filed, terminated, pending: IDB rebuild vs the
latest edition of Table C-1) using ``core.reconcile``.
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

from courts_analyst.config import settings
from courts_analyst.core.courts import COURTS, CourtLevel
from courts_analyst.core.db import Database
from courts_analyst.core.measures import get_measure
from courts_analyst.core.reconcile import TOLERANCES, VarianceRow, variance_rows

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUT = ROOT / "docs" / "variance-report.md"
STATUSES = ("matched", "explained_variance", "unexplained")


def _pct(v: float | None) -> str:
    return "–" if v is None else f"{v:+.2f}%"


def _name(code: str) -> str:
    c = COURTS[code]
    return c.citation or c.name


def render(rows: list[VarianceRow], release: str) -> str:
    fys = sorted({r.fiscal_year for r in rows})
    lines = [
        "# Variance report: IDB rebuild vs official Table C-1",
        "",
        "<!-- Generated by `make variance-report` (core/reconcile.py). Don't edit. -->",
        "",
        f"Every district, circuit and the nation, FY{fys[0]}–FY{fys[-1]}: civil "
        "cases filed, terminated and pending rebuilt from the FJC civil IDB and "
        "compared with the **latest** edition of Table C-1 that prints the figure. "
        f"IDB release: {release}.",
        "",
        "Classification (see `core/reconcile.py`): **matched** within tolerance; "
        "**explained variance** when a quantified cause covers the gap (a restated "
        "figure the IDB matches, repeat records, undated reopenings, or snapshot "
        "drift within the allowance); otherwise **unexplained**.",
        "",
        "| Measure | Tolerance | Snapshot allowance |",
        "| --- | ---: | ---: |",
    ]
    for mid, t in TOLERANCES.items():
        lines.append(
            f"| {get_measure(mid).label} | {t.pct}% (min {t.abs}) | {t.snapshot_pct}% |"
        )
    lines += [
        "",
        "## Summary",
        "",
        "| Measure | Court-years | Matched | Explained | Unexplained |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for mid in TOLERANCES:
        sub = [r for r in rows if r.measure == mid]
        c = Counter(r.status for r in sub)
        lines.append(
            f"| {get_measure(mid).label} | {len(sub)} | {c['matched']} | "
            f"{c['explained_variance']} | {c['unexplained']} |"
        )
    causes = Counter(r.cause for r in rows if r.cause)
    lines += [
        "",
        "Explained variance by cause: "
        + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in causes.most_common())
        + ".",
    ]
    lines += [
        "",
        "## National",
        "",
        "| Measure | FY | Official | Edition | IDB | Variance | Status |",
        "| --- | ---: | ---: | --- | ---: | ---: | --- |",
    ]
    for r in rows:
        if r.court == "US":
            status = r.status.replace("_", " ")
            if r.cause:
                status += f" ({r.cause.replace('_', ' ')})"
            lines.append(
                f"| {get_measure(r.measure).label} | {r.fiscal_year} | "
                f"{r.official:,.0f} | {r.edition} | {r.idb:,} | "
                f"{_pct(r.variance_pct)} | {status} |"
            )
    unexplained = sorted(
        (r for r in rows if r.status == "unexplained"), key=lambda r: -abs(r.variance)
    )
    lines += [
        "",
        f"## Unexplained ({len(unexplained)})",
        "",
        "Largest first. These are open questions for the domain expert "
        "(issue #11 tracks the pending-count reconstruction).",
        "",
        "| Measure | Court | FY | Official | IDB | Variance |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for r in unexplained:
        lines.append(
            f"| {get_measure(r.measure).label} | {_name(r.court)} | {r.fiscal_year} | "
            f"{r.official:,.0f} | {r.idb:,} | "
            f"{r.variance:+,.0f} ({_pct(r.variance_pct)}) |"
        )
    explained = [r for r in rows if r.status == "explained_variance"]
    lines += [
        "",
        f"## Explained variance ({len(explained)})",
        "",
        "| Measure | Court | FY | Official | IDB | Variance | Cause |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in sorted(explained, key=lambda r: (r.measure, r.court, r.fiscal_year)):
        lines.append(
            f"| {get_measure(r.measure).label} | {_name(r.court)} | {r.fiscal_year} | "
            f"{r.official:,.0f} | {r.idb:,} | {_pct(r.variance_pct)} | "
            f"{(r.cause or '').replace('_', ' ')} |"
        )
    districts = [r for r in rows if COURTS[r.court].level is CourtLevel.DISTRICT]
    worst = Counter(r.court for r in districts if r.status == "unexplained")
    if worst:
        lines += [
            "",
            "Districts with the most unexplained court-years: "
            + ", ".join(f"{_name(c)} ({n})" for c, n in worst.most_common(8))
            + ".",
        ]
    return "\n".join(lines) + "\n"


def write_variance_report(db: Database, out: Path, fys: list[int]) -> list[VarianceRow]:
    rows = variance_rows(db, fys)
    rel = db.one("SELECT coverage, last_modified FROM idb.idb_release LIMIT 1")
    release = f"{rel[1]}, “{rel[0]}”" if rel else "unknown"
    out.write_text(render(rows, release))
    return rows


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="courts_analyst.pipeline.reports")
    sub = p.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("variance", help="Write docs/variance-report.md")
    v.add_argument("--out", type=Path, default=DEFAULT_OUT)
    v.add_argument("--fy-from", type=int, default=2016)
    v.add_argument("--fy-to", type=int, default=2025)
    args = p.parse_args(argv)
    db = Database(settings.resolved_duckdb_path, settings.resolved_idb_path)
    rows = write_variance_report(
        db, args.out, list(range(args.fy_from, args.fy_to + 1))
    )
    c: Counter[str] = Counter(r.status for r in rows)
    print(f"{len(rows)} court-years: " + ", ".join(f"{k} {c[k]}" for k in STATUSES))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
