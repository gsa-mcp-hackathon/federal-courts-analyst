"""Generate ``docs/data-profile.md`` from a built ``idb.duckdb``.

Rows per fiscal year and per district, null rates, code distributions,
unknown-code counts and the data-break registry, so anyone can see what the
load produced without opening the database. Regenerated by every build.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

import duckdb

from courts_analyst.core.courts import COURTS
from courts_analyst.pipeline.idb.load import DECODED

PENDING_AT = """
    SELECT count(*) FROM idb_civil_record
    WHERE filing_date_ao <= DATE '{d}'
      AND (termination_date_ao IS NULL OR termination_date_ao > DATE '{d}')
      AND (prev_termination_date_ao IS NULL OR prev_termination_date_ao <= DATE '{d}')
"""
"""Records pending on date ``d``. A repeat record counts only after the prior
termination (the reopening date isn't recorded; see the methodology)."""


def _fmt(n: object) -> str:
    if n is None:
        return "–"
    if isinstance(n, float):
        return f"{n:.1f}"
    return f"{n:,}" if isinstance(n, int) else str(n)


def _table(
    headers: list[str], rows: Sequence[tuple[object, ...]], right: int = 1
) -> str:
    align = ["---"] * right + ["---:"] * (len(headers) - right)
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(align) + " |"]
    out += ["| " + " | ".join(_fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def write_profile(db_path: Path, out: Path) -> None:
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        text = _profile(con)
    finally:
        con.close()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)


def _profile(con: duckdb.DuckDBPyConnection) -> str:
    rel = con.execute("SELECT * FROM idb_release").fetchone()
    assert rel is not None
    cols = [d[0] for d in con.description]
    r = dict(zip(cols, rel, strict=True))
    fy_from, fy_to = r["fy_from"], r["fy_to"]
    parts = [
        "# Civil IDB data profile",
        "",
        "Generated by `make data-idb` from `data/build/idb.duckdb`. Don't edit by "
        "hand. Method and definitions: [methodology/idb.md](methodology/idb.md).",
        "",
        "## Release",
        "",
        _table(
            ["Item", "Value"],
            [
                ("File", f"[{r['url'].rsplit('/', 1)[-1]}]({r['url']})"),
                ("FJC coverage", r["coverage"]),
                ("Last-Modified", r["last_modified"]),
                ("sha256", f"`{r['sha256']}`"),
                ("Records in release", r["release_rows"]),
                ("Scope", f"cases active in FY{fy_from}–FY{fy_to}"),
                ("Rows repaired (quoted tabs)", r["repaired_rows"]),
                ("Control bytes replaced", r["control_bytes"]),
                ("Non-ASCII bytes (read as Latin-1)", r["non_ascii_bytes"]),
            ],
            right=2,
        ),
        "",
    ]

    counts = con.execute(
        """SELECT (SELECT count(*) FROM idb_civil_record),
                  (SELECT count(*) FROM idb_civil),
                  (SELECT count(*) FROM idb_civil_record WHERE is_repeat_record),
                  (SELECT count(*) FROM idb_civil_record WHERE status_code = 'S')"""
    ).fetchone()
    assert counts is not None
    parts += [
        "## Records and cases",
        "",
        _table(
            ["", "Rows"],
            [
                ("Records in scope (`idb_civil_record`)", counts[0]),
                ("Cases (`idb_civil`, latest record per case)", counts[1]),
                ("Repeat records (case terminated more than once)", counts[2]),
                ("Pending records (status as of the release)", counts[3]),
            ],
        ),
        "",
        "## By fiscal year",
        "",
        "Filed = cases by AO filing date (one per case). Terminated = terminated "
        "records by AO termination date. Pending = records pending on September 30.",
        "",
    ]
    rows = []
    for fy in range(fy_from, fy_to + 2):
        filed, mdl, term = con.execute(
            f"""SELECT
                  (SELECT count(*) FROM idb_civil WHERE filing_fy = {fy}),
                  (SELECT count(*) FROM idb_civil WHERE filing_fy = {fy}
                       AND is_mdl_direct_filed),
                  (SELECT count(*) FROM idb_civil_terminations
                       WHERE termination_fy = {fy})"""
        ).fetchone() or (0, 0, 0)
        if fy > fy_to:  # partial year: filings out of scope, Sep 30 not reached
            rows.append((f"FY{fy} (partial)", None, None, term, None))
            continue
        pending = con.execute(PENDING_AT.format(d=f"{fy}-09-30")).fetchone()
        rows.append((f"FY{fy}", filed, mdl, term, pending[0] if pending else None))
    parts += [
        _table(
            ["Fiscal year", "Filed", "MDL direct-filed", "Terminated", "Pending"], rows
        ),
        "",
        f"FY{fy_to + 1} is partial: the release ends before September 30, and "
        f"only cases filed by the end of FY{fy_to} are in scope, so it shows "
        "terminations of those cases only.",
        "",
    ]

    by_court = con.execute(
        f"""SELECT court,
              count(*) FILTER (WHERE filing_fy BETWEEN {fy_from} AND {fy_to}),
              count(*) FILTER (WHERE filing_fy BETWEEN {fy_from} AND {fy_to}
                               AND is_mdl_direct_filed),
              (SELECT count(*) FROM idb_civil_terminations t
               WHERE t.court = c.court
                 AND termination_fy BETWEEN {fy_from} AND {fy_to})
            FROM idb_civil c GROUP BY court"""
    ).fetchall()
    order = {code: i for i, code in enumerate(COURTS)}
    by_court.sort(key=lambda x: order.get(x[0], 999))
    parts += [
        f"## By district, FY{fy_from}–FY{fy_to}",
        "",
        _table(
            ["District", "Name", "Filed", "MDL direct-filed", "Terminated"],
            [(c, COURTS[c].name, f, m, t) for c, f, m, t in by_court],
            right=2,
        ),
        "",
    ]

    nulls = _null_rates(con)
    parts += [
        "## Null rates (`idb_civil_record`)",
        "",
        "Share of records where the column is NULL (missing, not applicable, or "
        "coded -8). Columns that are never NULL are omitted.",
        "",
        _table(["Column", "Null %"], [(c, p) for c, p in nulls if p > 0]),
        "",
    ]

    unknown = con.execute(
        "SELECT col, code, records FROM idb_unknown_code ORDER BY col, code"
    ).fetchall()
    total = counts[0]
    parts += ["## Codes not in the codebook", ""]
    if unknown:
        per_col: dict[str, int] = {}
        for col, _, n in unknown:
            per_col[col] = per_col.get(col, 0) + n
        parts += [
            "Decoded as `UNKNOWN(<code>)`; never dropped.",
            "",
            _table(
                ["Column", "Code", "Records", "Column rate %"],
                [
                    (col, code, n, round(100 * per_col[col] / total, 4))
                    for col, code, n in unknown
                ],
                right=2,
            ),
            "",
        ]
    else:
        parts += ["None.", ""]
    discontinued = con.execute(
        """SELECT nos_code, nos, count(*) FROM idb_civil_record r
           JOIN code_nos k ON k.code = r.nos_code WHERE k.discontinued
           GROUP BY ALL ORDER BY 1"""
    ).fetchall()
    if discontinued:
        parts += [
            "Discontinued nature-of-suit codes still present (labelled from Table "
            "C-2 and the JS 44):",
            "",
            _table(["Code", "Label", "Records"], discontinued, right=2),
            "",
        ]

    parts += ["## Code distributions", ""]
    for column, out in DECODED.items():
        dist = con.execute(
            f"""SELECT coalesce({out}_code, '(missing)'), coalesce({out}, ''),
                       count(*), round(100.0 * count(*) / {total}, 2)
                FROM idb_civil_record GROUP BY ALL ORDER BY 3 DESC LIMIT 25"""
        ).fetchall()
        parts += [
            f"### {column}",
            "",
            _table(["Code", "Label", "Records", "%"], dist, right=2),
            "",
        ]

    breaks = con.execute(
        "SELECT date, kind, field, summary FROM data_breaks ORDER BY date"
    ).fetchall()
    parts += [
        "## Data breaks",
        "",
        "From `pipeline/idb/data_breaks.yaml`; details in the `data_breaks` table.",
        "",
        _table(["Date", "Kind", "Field", "Summary"], breaks, right=4),
        "",
    ]
    return "\n".join(parts)


def _null_rates(con: duckdb.DuckDBPyConnection) -> list[tuple[str, float]]:
    cols = [
        c[0]
        for c in con.execute("DESCRIBE idb_civil_record").fetchall()
        if c[0] != "codes_outside_validity"
    ]
    exprs = ", ".join(f"avg(({c} IS NULL)::INTEGER)" for c in cols)
    row = con.execute(f"SELECT {exprs} FROM idb_civil_record").fetchone()
    assert row is not None
    return [(c, round(100 * float(v or 0), 2)) for c, v in zip(cols, row, strict=True)]
